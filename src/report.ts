// Stage 7: REPORT. Internal evidence sheet per finding, for a human to turn into an upstream issue.
// Nothing is posted anywhere. The model only writes the "why the rewrite is not equivalent" paragraph.
import { chat } from "./llm";
import { MODELS } from "./config";
import type { DedupResult } from "./dedup";
import type { Finding, ProgramResult } from "./oracles";
import type { RuleInfo } from "./tools/types";
import type { Verdict } from "./judge";

export type ReportInput = {
  tool: string; version: string; info: RuleInfo; finding: Finding; result: ProgramResult;
  minimized: { code: string; lines: { before: number; after: number } };
  dedup: DedupResult; commands: string[]; runner: string; verdict?: Verdict; fence?: string;
};

/** The one model-written paragraph of an evidence sheet: why the rewrite is not equivalent. Advisory; never a verdict. */
export async function explainRewrite(inp: { tool: string; rule: string; safe: boolean; program: string; diff: string; kind: string; detail: string }): Promise<{ text: string; cost: number }> {
  const r = await chat({
    model: MODELS.mid,
    messages: [
      { role: "system", content: "You are a compiler engineer explaining, precisely and briefly, why an automatic code rewrite is not semantics-preserving. Plain prose, no headings, no bullet points, at most 120 words. Do not speculate about the tool's implementation." },
      { role: "user", content: `Tool ${inp.tool}, rule ${inp.rule}. The fix is labelled ${inp.safe ? "safe" : "unsafe"}.\nProgram:\n${inp.program}\nDiff applied by the fix:\n${inp.diff}\nObserved: ${inp.kind}. ${inp.detail}\n\nExplain why the rewritten program behaves differently.` },
    ],
    maxTokens: 500,
    temperature: 0.3,
    tag: "report",
  });
  return { text: r.text.trim(), cost: r.cost };
}

export async function writeReport(inp: ReportInput): Promise<{ markdown: string; cost: number; explanation: string }> {
  const { finding, result, info } = inp;
  const explain = await explainRewrite({ tool: inp.tool, rule: info.rule, safe: finding.safeLabel, program: inp.minimized.code, diff: result.after?.diff ?? "(none)", kind: finding.kind, detail: finding.detail });
  const dups = inp.dedup.verdicts.filter((v) => v.relation !== "unrelated");
  const md = `# ${inp.tool} ${info.rule}: ${title(finding)}

Internal evidence sheet generated by fixhunt. Not an issue text. A human re-verifies, checks the duplicates
below, and writes the upstream report in their own words following the project's AI policy.

- Tool: ${inp.tool} ${inp.version}
- Rule: ${info.rule} (tool labels the fix: ${info.fixKind}${finding.safeLabel ? ", this fix reported as safe" : ""})
- Oracle: ${finding.kind}
- Judge (Nemotron 3 Ultra, advisory): ${inp.verdict ? `${inp.verdict.grade}, severity ${inp.verdict.severity}. ${inp.verdict.why}` : "not run"}
- Program: minimized from ${inp.minimized.lines.before} to ${inp.minimized.lines.after} lines

## Reproducer

\`\`\`${inp.fence ?? ""}
${inp.minimized.code.trimEnd()}
\`\`\`

## Commands

\`\`\`sh
${inp.commands.join("\n")}
\`\`\`

## Observed

${fence(finding.detail)}

## Diff applied by the fix

\`\`\`diff
${(result.after?.diff ?? "").trimEnd()}
\`\`\`

## Why the rewrite is not equivalent (model draft, verify before use)

${explain.text}

## Upstream search

Queries: ${inp.dedup.queries.map((q) => `"${q}"`).join(", ")}

${dups.length ? dups.map((v) => `- ${v.relation}: ${v.url}\n  ${v.why}`).join("\n") : "- no duplicate or related report found among " + inp.dedup.hits.length + " hits"}
${inp.dedup.hits.length ? "\n<details><summary>All hits</summary>\n\n" + inp.dedup.hits.map((h) => `- [${h.source}${h.state ? ", " + h.state : ""}] ${h.title} — ${h.url}`).join("\n") + "\n\n</details>" : ""}
`;
  return { markdown: md, cost: explain.cost, explanation: explain.text };
}

function title(f: Finding): string {
  switch (f.kind) {
    case "fix-changes-behavior": return "fix changes program behavior";
    case "fix-breaks-syntax": return "fixed output does not parse";
    case "fix-not-fixpoint": return "fix is not a fixpoint";
    case "fix-introduces-diagnostic": return "fix introduces new diagnostics";
    case "tool-crash": return "tool crashes";
    default: return f.kind;
  }
}
function fence(s: string) { return "```\n" + s.trim() + "\n```"; }
